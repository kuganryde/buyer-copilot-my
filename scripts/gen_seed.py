#!/usr/bin/env python3
"""Generate db/seed.sql from db/directory_seed.json (single source of truth).

CI runs `gen_seed.py --check` so the committed SQL can never drift from the JSON
that the engine's in-memory mode and the tests use.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "db" / "directory_seed.json"
OUT = ROOT / "db" / "seed.sql"
COLS = ["agency_name", "category", "jurisdiction_state", "official_url", "contact_details",
        "summary_rule", "last_verified_date", "is_active", "is_proposed_pending_gazette"]


def lit(v: object) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    # Dollar-quoting with a fixed tag cannot be broken out of unless the tag appears in data.
    s = str(v)
    if "$seed$" in s:
        raise ValueError("forbidden token in seed data")
    return f"$seed${s}$seed$"


def render() -> str:
    rows = json.loads(SRC.read_text(encoding="utf-8"))
    lines = ["-- GENERATED by scripts/gen_seed.py from db/directory_seed.json — do not edit by hand.",
             "BEGIN;",
             f"INSERT INTO directory_entries ({', '.join(COLS)}) VALUES"]
    vals = []
    for r in rows:
        missing = [c for c in COLS if c not in r]
        if missing:
            raise ValueError(f"{r.get('agency_name')}: missing {missing}")
        if not r["official_url"].startswith("https://"):
            raise ValueError(f"{r['agency_name']}: official_url must be https")
        vals.append("  (" + ", ".join(lit(r[c]) for c in COLS) + ")")
    lines.append(",\n".join(vals))
    lines.append("ON CONFLICT (agency_name, jurisdiction_state) DO UPDATE SET\n  " + ",\n  ".join(
        f"{c} = EXCLUDED.{c}" for c in COLS if c not in ("agency_name", "jurisdiction_state")
        and c != "last_verified_date") + ",\n  updated_at = now();")
    lines.append("COMMIT;")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sql = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != sql:
            print("db/seed.sql is out of date: run scripts/gen_seed.py", file=sys.stderr)
            sys.exit(1)
        print("seed.sql up to date")
    else:
        OUT.write_text(sql, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
